import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import createTracer from '../web/rust-tracer.mjs';
import {traceFixed,curveRuntime} from '../web/desktop-curves.mjs';
import {pixelCenterError,binaryGridClasses} from '../web/pixel-grid-trace.mjs';
import {auditNative} from '../web/geometry.mjs';
const runtime=await createTracer({wasmBinary:await fs.readFile('web/doctortracer.wasm')});
await curveRuntime({maskBinary:await fs.readFile('web/vendor/mask.wasm'),pathBinary:await fs.readFile('web/vendor/pathkit.wasm')});
await auditNative('<svg/>',{wasmBinary:await fs.readFile('web/vendor/audit.wasm')});
const w=160,h=144;
const raster=predicate=>{const p=new Uint8Array(w*h*4);for(let y=0;y<h;y++)for(let x=0;x<w;x++){const i=4*(y*w+x);p.set(predicate(x+.5,y+.5)?[0,0,0,255]:[255,255,255,255],i);}return p;};
const opts={category:'hard',colors:2,detail:2,speckle:0,polygon:false,gpu:false,smooth:true,inputDpi:600};
const run=(r,config={})=>traceFixed(runtime,r,w,h,{...opts,...config});
const circle=raster((x,y)=>(x-80)**2+(y-72)**2<46**2);
const a=await run(circle);
if(!a.pixelGridFit){
 const paletteBytes=runtime.stage(circle,w,h,{kind:2,colors:2});
 const palette=Array.from({length:paletteBytes.length/3},(_,i)=>Array.from(paletteBytes.slice(i*3,i*3+3)));
 const labels=runtime.stage(circle,w,h,{kind:3,palette,extra:0});
 const cleaned=runtime.stage(labels,w,h,{kind:4,palette,colors:palette.length,extra:1});
 const shared=Int32Array.from(cleaned,v=>v===255?-1:v);
 console.log('GRID DEBUG',JSON.stringify({palette,classes:binaryGridClasses(shared,palette,w,h)}));
 const {fitPixelGrid}=await import('../web/pixel-grid-trace.mjs');
 const {traceMask}=await import('../web/desktop-curves.mjs');
 const report=value=>console.log('FIT DEBUG',JSON.stringify(value));
 const silent=await fitPixelGrid(shared,palette,w,h,{curveRuntime,traceMask,audit:async()=>{},inputDpi:600,limitFraction:1,report});
 console.log('FIT WITHOUT AUDIT',silent?.metrics||null);
 await fitPixelGrid(shared,palette,w,h,{curveRuntime,traceMask,audit:auditNative,inputDpi:600,limitFraction:1,report});
}
assert.ok(a.pixelGridFit,'Expected Potrace quantization path to be accepted');
assert.equal(a.pixelGridFit.inputDpi,600);assert.equal(a.pixelGridFit.pixelPitchMm,25.4/600);
assert.ok(a.pixelGridFit.bezierSegments>=4);assert.ok(a.pixelGridFit.mismatchedPixelCenters<=a.pixelGridFit.allowedErrors);
assert.match(a.svg,/data-quantization-band-px="0.5"/);assert.match(a.svg,/data-boundary-contract="paired"/);
assert.equal((await run(circle)).svg,a.svg,'deterministic output');
const rect=await run(raster((x,y)=>x>=20&&x<130&&y>=16&&y<109));
assert.equal(rect.pixelGridFit,undefined);assert.doesNotMatch(rect.svg,/\bC[-\d. ]/);
const forced=await run(circle,{polygon:true});assert.doesNotMatch(forced.svg,/\bC[-\d. ]/);
const ring=await run(raster((x,y)=>{const v=(x-80)**2+(y-72)**2;return v<46**2&&v>21**2;}));
assert.ok(ring.pixelGridFit,'a hole must be preserved with paired paths');
const ellipse=await run(raster((x,y)=>((x-80)/54)**2+((y-72)/31)**2<1));
assert.ok(ellipse.pixelGridFit,'ellipse must fit quantized pixel cells');
const mixed=await run(raster((x,y)=>(x>=12&&x<38&&y>=14&&y<49)||((x-105)**2+(y-78)**2<32**2)));
assert.match(mixed.svg,/data-boundary-contract="paired"/);
assert.equal(binaryGridClasses(new Int32Array(24),[[0,0,0]],6,4),null);
assert.ok(pixelCenterError('M0 0 L3 0 L3 3 L0 3 Z',new Uint8Array(16),4,4)>0);
for(const v of [a,rect,forced,ring,ellipse,mixed]){assert.ok(!v.svg.includes('NaN'));assert.deepEqual(v.geometry?.issues||[],[]);}
console.log('PASS Potrace native pixel-aware fitting: circle ellipse ring sharp rectangle corner, paired colors, exact pixel-center fidelity',a.pixelGridFit);
